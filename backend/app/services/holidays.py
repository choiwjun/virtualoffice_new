"""
한국 공휴일 정적 소스 (B-18, D17 — daily_reports 배치 공휴일 스킵).

외부 API/네트워크·자격증명 없이 결정론적으로 동작하는 정적 테이블(단일 진입점 `is_kr_holiday`).
- **양력 고정 공휴일**: 매년 동일한 (월, 일) — 연도 무관.
- **변동 공휴일**: 음력(설날/추석/부처님오신날) + 대체공휴일(대체휴일)은 연도마다 그레고리력 날짜가
  달라 연도별 ISO 날짜로 명시한다.

출처: 우주항공청(KASI) 월력요항 + publicholidays.co.kr(law.go.kr 관공서 공휴일 규정 근거). 2026~2027 커버.
제헌절(7/17)은 2008년 공휴일에서 제외됐다가 **법률 제21338호(시행 2026-05-11)로 재지정**되어 2026년부터
다시 법정 공휴일이다 → 양력 고정에 포함한다.

**유지보수**: `_VARIABLE_HOLIDAYS`는 2026~2027만 정밀 커버한다(2028+ 음력/대체공휴일은 관보 확정 후 추가).
운영이 커버 범위 밖으로 이어지면 daily_reports_push가 WARN 로그로 테이블 갱신을 촉구한다. 양력 고정
공휴일은 모든 연도에 적용된다.
공공 API(한국천문연 특일정보) 연동으로 소스를 교체하려면 `is_kr_holiday` 단일 진입점만 바꾸면 된다.
"""

from datetime import date

# 양력 고정 공휴일 (월, 일) — 연도 무관.
_FIXED_SOLAR: frozenset[tuple[int, int]] = frozenset(
    {
        (1, 1),    # 신정
        (3, 1),    # 삼일절
        (5, 5),    # 어린이날
        (6, 6),    # 현충일
        (7, 17),   # 제헌절(법률 제21338호 시행 2026-05-11 재지정 — 2026년부터)
        (8, 15),   # 광복절
        (10, 3),   # 개천절
        (10, 9),   # 한글날
        (12, 25),  # 성탄절
    }
)

# 연도별 정밀 커버 범위(테스트/진단용). 이 범위 밖 연도는 양력 고정 공휴일만 판정된다.
VARIABLE_COVERED_YEARS: frozenset[int] = frozenset({2026, 2027})

# 변동 공휴일(음력 + 대체공휴일) — 연도별 ISO(YYYY-MM-DD) 명시.
_VARIABLE_HOLIDAYS: frozenset[str] = frozenset(
    {
        # ── 2026 ──
        "2026-02-16", "2026-02-17", "2026-02-18",  # 설날 연휴
        "2026-03-02",                               # 삼일절 대체(3/1 일)
        "2026-05-24", "2026-05-25",                 # 부처님오신날 + 대체(일)
        "2026-08-17",                               # 광복절 대체(8/15 토)
        "2026-09-24", "2026-09-25", "2026-09-26",  # 추석 연휴
        "2026-10-05",                               # 개천절 대체(10/3 토)
        # ── 2027 ──
        "2027-02-06", "2027-02-07", "2027-02-08", "2027-02-09",  # 설날 연휴 + 대체
        "2027-05-13",                               # 부처님오신날
        "2027-06-07",                               # 현충일 대체(6/6 일)
        "2027-07-19",                               # 제헌절 대체(7/17 토)
        "2027-08-16",                               # 광복절 대체(8/15 일)
        "2027-09-14", "2027-09-15", "2027-09-16",  # 추석 연휴
        "2027-10-04",                               # 개천절 대체(10/3 일)
        "2027-10-11",                               # 한글날 대체(10/9 토)
        "2027-12-27",                               # 성탄절 대체(12/25 토)
        # (2028+ 음력/대체공휴일은 관보 확정 후 추가 — 현재 미커버, daily_reports_push가 WARN)
    }
)


def is_kr_holiday(d: date) -> bool:
    """``d``(한국 로컬 날짜)가 법정 공휴일이면 True (정적 소스 기준, B-18).

    양력 고정 공휴일은 모든 연도에, 음력/대체공휴일은 ``VARIABLE_COVERED_YEARS`` 범위 내에서 판정된다.
    """
    if (d.month, d.day) in _FIXED_SOLAR:
        return True
    return d.isoformat() in _VARIABLE_HOLIDAYS
